def write_crlf_no_bom(path: Path, lines: list[str]) -> None:
    """The PS1 writer's exact byte behavior: WriteAllLines = line + CRLF each."""
    data = ("\r\n".join(lines) + "\r\n").encode("utf-8")
    path.write_bytes(data)


