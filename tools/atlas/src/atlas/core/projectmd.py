"""PROJECT.md / control-plane file generation.

Byte-parity contract with New-Project.ps1 (the PS1 tools stay alive until P4,
and Norma + PRD-209's identity chain parse these files): UTF-8 with NO BOM,
CRLF line endings, trailing newline, identical line content - with exactly two
sanctioned divergences, both asserted by the golden test:

1. Attribution line says "Generated by Atlas." (not "Generated by New-Project.").
2. The canonical-map section is wrapped in <!-- atlas:map-begin/end --> markers
   so Doctor --fix-project-md can regenerate it idempotently (spec 5.6).
"""

